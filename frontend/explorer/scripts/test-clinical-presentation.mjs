import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { transform } from 'esbuild';
const compiled = await transform(await readFile('src/clinicalPresentation.ts','utf8'), {loader:'ts',format:'esm'});
const {clinicalFacts,clinicalTableSummary,clinicalPValue}=await import('data:text/javascript;base64,'+Buffer.from(compiled.code).toString('base64'));
const fact={endpoint:{label_ko:'수축기 혈압',unit:'mmHg'},comparison:{arm:'대조군'},observations:[{time_label:'baseline',value:0},{time_label:'5 years',value:150.1}],statistical_tests:[{reported_label:'ns',p_value:null}]};
const row={effect:null,context:{clinical_endpoints:[fact]}};
assert.equal(clinicalFacts(row)[0],fact);
assert.equal(clinicalFacts({metadata:{clinical_endpoints:[fact]}})[0],fact);
assert.deepEqual(clinicalFacts(null),[]);
assert.deepEqual(clinicalFacts({context:{clinical_endpoints:[null,0,'bad']}}),[]);
assert.equal(clinicalTableSummary(row).title,'수축기 혈압 · 대조군');
assert.match(clinicalTableSummary(row).values,/baseline: 0 mmHg/);
assert.match(clinicalTableSummary(row).scope,/단일 치료 효과 아님/);
assert.equal(clinicalPValue({reported_label:'ns',p_value:null}),'ns');
assert.equal(clinicalPValue({p_value:0}),'0');
assert.equal(clinicalPValue({p_value:null}),'미보고');
assert.equal(clinicalPValue({reported_label:'<0.001',p_value:null}),'<0.001');
console.log('11 clinical summary checks passed; zero, ns, inequalities and test scopes preserved');
